TERMUX_PKG_VERSION="0.14.0"
TERMUX_PKG_SRCURL="https://files.pythonhosted.org/packages/c3/7d/d9daedf0f2ebcacd20d599928f8913e9d2aea1d56d2d355a93bfa2b611d7/fastuuid-0.14.0.tar.gz"
